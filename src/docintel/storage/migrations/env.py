"""
Open Doc Intelligence (docintel) - Alembic Environment Configuration
Supports both PostgreSQL (psycopg2) and SQLite sync drivers for migration execution,
with batch-mode schema manipulation and Base.metadata introspection.
"""

from logging.config import fileConfig
import sys

from alembic import context
from sqlalchemy import engine_from_config, pool

from docintel.config.settings import get_settings
from docintel.storage.models import Base

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Interpret the config file for Python logging.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Set target metadata for autogenerate support
target_metadata = Base.metadata


def get_sync_url() -> str:
    """Obtain sync database URL from application settings."""
    settings = get_settings()
    return settings.sync_database_url


def run_migrations_offline() -> None:
    """
    Run migrations in 'offline' mode.
    Configures the context with just a URL and not an Engine.
    """
    url = config.get_main_option("sqlalchemy.url") or get_sync_url()
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        render_as_batch=True,  # Enables batch mode for SQLite compatibility
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """
    Run migrations in 'online' mode.
    Creates an Engine and associates a connection with the context.
    """
    db_url = config.get_main_option("sqlalchemy.url") or get_sync_url()
    configuration = config.get_section(config.config_ini_section) or {}
    configuration["sqlalchemy.url"] = db_url

    connectable = engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            render_as_batch=True,  # Crucial for SQLite ALTER TABLE support
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
